func unhex(c byte) int {
	switch {
	case c >= '0' && c <= '9':
		return int(c - '0')
	case c >= 'a' && c <= 'f':
		return int(c-'a') + 10
	case c >= 'A' && c <= 'F':
		return int(c-'A') + 10
	}
	return -1
}

func runJA4(t *testing.T, name, hexStr string) JA4Result {
	t.Helper()
	raw := make([]byte, len(hexStr)/2)
	for i := 0; i+1 < len(hexStr); i += 2 {
		hi := unhex(hexStr[i])
		lo := unhex(hexStr[i+1])
		if hi < 0 || lo < 0 {
			t.Fatalf("%s: bad hex at %d", name, i)
		}
		raw[i/2] = byte(hi<<4 | lo)
	}
	br := bufio.NewReader(strings.NewReader(string(raw)))
	res, ok := ParseClientHelloJA4(br)
	if !ok {
		t.Fatalf("%s: parse failed", name)
	}
	t.Logf("%s JA4=%s grease=%v alpn=%s", name, res.JA4, res.HasGREASE, res.ALPN)
	return res
}

func TestJA4Chrome(t *testing.T) {
	r := runJA4(t, "chromium", vecChrome)
	if !r.TLS13 || r.ALPN != "h2" || !r.HasGREASE {
		t.Errorf("chromium: want TLS1.3+h2+GREASE, got %+v", r)
	}
	if !strings.HasPrefix(r.JA4, "t13d") {
		t.Errorf("chromium: JA4 prefix wrong")
	}
}

func TestJA4Curl(t *testing.T) {
	r := runJA4(t, "curl", vecCurl)
	if r.HasGREASE {
		t.Errorf("curl: GREASE should be absent")
	}
	if r.ALPN != "h2" || !r.TLS13 {
		t.Errorf("curl: want TLS1.3+h2, got %+v", r)
	}
}

func TestJA4GoNoALPN(t *testing.T) {
	r := runJA4(t, "go", vecGo)
	if r.HasGREASE {
		t.Errorf("go: GREASE should be absent")
	}
	if r.ALPN != "00" {
		t.Errorf("go: ALPN should be 00, got %s", r.ALPN)
	}
	if !strings.HasPrefix(r.JA4, "t13d") {
		t.Errorf("go: JA4 prefix wrong")
	}
}
